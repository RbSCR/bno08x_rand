  void TearDown() { imu_broadcaster_.reset(nullptr); }

  template <
    my_semantic_component::IMUSensorCovarianceOption sensor_option =
      my_semantic_component::IMUSensorCovarianceOption::WithCovariance>
  void setup_imu_covariance_broadcaster() {
    std::vector<LoanedStateInterface> state_ifs;
    state_ifs.emplace_back(imu_orientation_x_);
    state_ifs.emplace_back(imu_orientation_y_);
    state_ifs.emplace_back(imu_orientation_z_);
    state_ifs.emplace_back(imu_orientation_w_);

    state_ifs.emplace_back(imu_angular_velocity_x_);
    state_ifs.emplace_back(imu_angular_velocity_y_);
    state_ifs.emplace_back(imu_angular_velocity_z_);

    state_ifs.emplace_back(imu_linear_acceleration_x_);
    state_ifs.emplace_back(imu_linear_acceleration_y_);
    state_ifs.emplace_back(imu_linear_acceleration_z_);

    if constexpr (sensor_option == my_semantic_component::IMUSensorCovarianceOption::WithCovariance) {
      state_ifs.emplace_back(orientation_covariance_xx_);
      state_ifs.emplace_back(orientation_covariance_yy_);
      state_ifs.emplace_back(orientation_covariance_zz_);
      state_ifs.emplace_back(angular_velocity_covariance_xx_);
      state_ifs.emplace_back(angular_velocity_covariance_yy_);
      state_ifs.emplace_back(angular_velocity_covariance_zz_);
      state_ifs.emplace_back(linear_acceleration_covariance_xx_);
      state_ifs.emplace_back(linear_acceleration_covariance_yy_);
      state_ifs.emplace_back(linear_acceleration_covariance_zz_);
    }

    imu_broadcaster_->assign_interfaces({}, std::move(state_ifs));
  }

  sensor_msgs::msg::Imu subscribe_and_get_message() {
    rclcpp::Node test_subscription_node("test_subscription_node");
    auto subscription = test_subscription_node.create_subscription<sensor_msgs::msg::Imu>(
      "/test_imu_sensor_covariance_static_and_dynamic_broadcaster/imu", 10,
      [](const sensor_msgs::msg::Imu::SharedPtr) {});
    imu_broadcaster_->update(rclcpp::Time{}, rclcpp::Duration::from_seconds(0));
    wait_for(subscription);

    rclcpp::MessageInfo msg_info;
    sensor_msgs::msg::Imu imu_msg;
    subscription->take(imu_msg, msg_info);
    return imu_msg;
  }

  controller_interface::ControllerInterfaceParams create_ctrl_params(
    const rclcpp::NodeOptions & node_options, const std::string & robot_description = "") {
    controller_interface::ControllerInterfaceParams params;
    params.controller_name = "test_imu_sensor_covariance_static_and_dynamic_broadcaster";
    params.robot_description = robot_description;
    params.update_rate = 0;
    params.node_namespace = "";
    params.node_options = node_options;
    return params;
  }

