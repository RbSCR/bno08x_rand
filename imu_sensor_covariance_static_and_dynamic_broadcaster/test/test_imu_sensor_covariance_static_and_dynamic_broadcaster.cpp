TEST_F(
  IMUSensorCovarianceBroadcasterTest,
  whenBroadcasterReadsCovarianceFormInterfaceThenValusesShouldBroadcastedInMsg) {
  const auto node_options = create_node_options_with_overriden_parameters(
    {sensor_name_param_, frame_id_, {"read_covariance_from_interface", true}});

  const auto result = imu_broadcaster_->init(
    create_ctrl_params(node_options, ros2_control_test_assets::minimal_robot_urdf));
  ASSERT_EQ(result, controller_interface::return_type::OK);

  ASSERT_TRUE(configure_succeeds(imu_broadcaster_));

  setup_imu_covariance_broadcaster<
    my_semantic_component::IMUSensorCovarianceOption::WithCovariance>();

  ASSERT_TRUE(activate_succeeds(imu_broadcaster_));

  const auto imu_msg = subscribe_and_get_message();
  EXPECT_EQ(imu_msg.header.frame_id, frame_id_.get_value<std::string>());
  EXPECT_EQ(imu_msg.orientation.x, sensor_values_[0]);
  EXPECT_EQ(imu_msg.orientation.y, sensor_values_[1]);
  EXPECT_EQ(imu_msg.orientation.z, sensor_values_[2]);
  EXPECT_EQ(imu_msg.orientation.w, sensor_values_[3]);
  EXPECT_EQ(imu_msg.angular_velocity.x, sensor_values_[4]);
  EXPECT_EQ(imu_msg.angular_velocity.y, sensor_values_[5]);
  EXPECT_EQ(imu_msg.angular_velocity.z, sensor_values_[6]);
  EXPECT_EQ(imu_msg.linear_acceleration.x, sensor_values_[7]);
  EXPECT_EQ(imu_msg.linear_acceleration.y, sensor_values_[8]);
  EXPECT_EQ(imu_msg.linear_acceleration.z, sensor_values_[9]);

  const std::array<double, 9> expected_orientation_covariance = {
    {sensor_values_[10], 0.0, 0.0, 0.0, sensor_values_[11], 0.0, 0.0, 0.0, sensor_values_[12]}};
  ASSERT_THAT(
    imu_msg.orientation_covariance, ::testing::ElementsAreArray(expected_orientation_covariance));
  const std::array<double, 9> expected_angular_velocity_covariance = {
    {sensor_values_[13], 0.0, 0.0, 0.0, sensor_values_[14], 0.0, 0.0, 0.0, sensor_values_[15]}};
  ASSERT_THAT(
    imu_msg.angular_velocity_covariance,
    ::testing::ElementsAreArray(expected_angular_velocity_covariance));
  const std::array<double, 9> expected_linear_acceleration_covariance = {
    {sensor_values_[16], 0.0, 0.0, 0.0, sensor_values_[17], 0.0, 0.0, 0.0, sensor_values_[18]}};
  ASSERT_THAT(
    imu_msg.linear_acceleration_covariance,
    ::testing::ElementsAreArray(expected_linear_acceleration_covariance));
}
